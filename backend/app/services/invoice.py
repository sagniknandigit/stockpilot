"""Printable invoice / receipt for a sales order (PDF, generated server-side)."""

from datetime import datetime
from decimal import Decimal
from uuid import UUID

from fpdf import FPDF
from fpdf.enums import XPos, YPos
from sqlalchemy.ext.asyncio import AsyncSession

from app.models import Organization
from app.services.forecasting import org_timezone
from app.services.sales import get_order

INK = (15, 23, 42)
MUTED = (100, 116, 139)
ACCENT = (79, 70, 229)


def _money(currency: str, value: Decimal) -> str:
    # Core PDF fonts are Latin-1 only (no ₹ glyph), so use the ISO code.
    return f"{currency} {value:,.2f}"


async def render_invoice(db: AsyncSession, org_id: UUID, order_id: UUID) -> tuple[str, bytes]:
    order = await get_order(db, org_id, order_id)
    org = await db.get(Organization, org_id)
    assert org is not None
    tz = await org_timezone(db, org_id)
    issued = order.created_at.astimezone(tz)
    cur = org.currency

    pdf = FPDF(format="A4")
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.add_page()
    pdf.set_title(f"Invoice SO-{order.number}")
    pdf.set_author(org.name)

    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(*ACCENT)
    pdf.cell(0, 10, org.name, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(*MUTED)
    pdf.cell(
        0,
        5,
        f"Location: {order.location.name} ({order.location.code})",
        new_x=XPos.LMARGIN,
        new_y=YPos.NEXT,
    )
    pdf.ln(6)

    pdf.set_text_color(*INK)
    pdf.set_font("Helvetica", "B", 13)
    pdf.cell(0, 8, f"Invoice SO-{order.number}", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_font("Helvetica", "", 10)
    meta = [
        ("Date", f"{issued:%d %b %Y, %H:%M} ({tz.key})"),
        ("Customer", order.customer_name or "Walk-in customer"),
        ("Status", order.status.value.replace("_", " ").title()),
    ]
    for label, value in meta:
        pdf.set_text_color(*MUTED)
        pdf.cell(28, 6, label)
        pdf.set_text_color(*INK)
        pdf.cell(0, 6, value, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.ln(4)

    widths = (30, 78, 16, 32, 34)
    headers = ("SKU", "Item", "Qty", "Unit price", "Amount")
    pdf.set_fill_color(241, 245, 249)
    pdf.set_font("Helvetica", "B", 9)
    for width, header in zip(widths, headers, strict=True):
        align = "R" if header in ("Qty", "Unit price", "Amount") else "L"
        pdf.cell(width, 8, header, fill=True, align=align)
    pdf.ln()
    pdf.set_font("Helvetica", "", 9)
    for line in order.lines:
        name = line.name if len(line.name) <= 48 else line.name[:45] + "..."
        if line.refunded_quantity:
            name += f" (refunded {line.refunded_quantity})"
        cells = (
            (line.sku, "L"),
            (name, "L"),
            (str(line.quantity), "R"),
            (_money(cur, line.unit_price), "R"),
            (_money(cur, line.line_total), "R"),
        )
        for width, (value, align) in zip(widths, cells, strict=True):
            pdf.cell(width, 7, value.encode("latin-1", "replace").decode("latin-1"), align=align)
        pdf.ln()
    pdf.ln(3)

    def total_row(label: str, value: str, bold: bool = False) -> None:
        pdf.set_font("Helvetica", "B" if bold else "", 10)
        pdf.cell(sum(widths) - 40, 7, label, align="R")
        pdf.cell(40, 7, value, align="R", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    total_row("Subtotal", _money(cur, order.subtotal))
    if order.discount:
        total_row("Discount", "-" + _money(cur, order.discount))
    total_row("Total", _money(cur, order.total), bold=True)
    if order.refunded_amount:
        total_row("Refunded", "-" + _money(cur, order.refunded_amount))
        total_row("Net paid", _money(cur, order.total - order.refunded_amount), bold=True)

    pdf.ln(10)
    pdf.set_font("Helvetica", "", 8)
    pdf.set_text_color(*MUTED)
    pdf.cell(
        0, 5, f"Generated by StockPilot on {datetime.now(tz):%d %b %Y %H:%M}. Thank you!", align="C"
    )
    return f"SO-{order.number}.pdf", bytes(pdf.output())
